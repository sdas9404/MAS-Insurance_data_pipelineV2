def define(name):
    if name in OBS: return OBS[name]
    if name in PARAMETERS: return PARAMETERS[name]
    for prefix in ['collider_','victim_','ego_','foe_','a_','b_']:
        if name.startswith(prefix) and name[len(prefix):] in OBS:
            u,d=OBS[name[len(prefix):]]; return u,prefix[:-1]+' participant: '+d
    for metric in ['minTTC','maxDRAC','PET','minPPET','maxMDRAC']:
        if name.startswith(metric+'_'):
            field=name[len(metric)+1:]
            unit='m/s2' if metric in ['maxDRAC','maxMDRAC'] else 's'
            return {'type':'code','position':'m,m','time':'s','speed':'m/s'}.get(field,unit),f'Native SUMO {metric} {field}; not a count of crashes; NA maps to null'
    for metric,unit in [('headway','s'),('ttc','s'),('speed','m/s'),('acceleration','m/s2')]:
        if name.startswith(metric+'_p'): return unit, f'Empirical percentile {name.rsplit("p",1)[1]} of defined sampled {metric} in driver/run'
    if name.endswith('_per_100km'): return 'events/100 km','Corresponding event count *100000 / TripInfo distance_m; null for zero exposure'
    if name.endswith('_per_hour'): return 'events/hour','Corresponding event count *3600 / TripInfo travel_duration_s; null for zero exposure'
    if name.endswith('_missing_fraction'): return '1','1 - defined samples / total retained telemetry samples'
    if name.endswith('_defined_samples'): return 'count','Number of non-null retained values for this observation'
    if name.endswith('_episodes'): return 'count','Number of coalesced observed episodes of '+name[:-9]+'; see event thresholds'
    if name.endswith('_mps2'): return 'm/s2',name.replace('_',' ')+' computed from observed acceleration'
    if name.endswith('_mps'): return 'm/s',name.replace('_',' ')+' computed over retained telemetry'
    if name.endswith('_s'): return 's',name.replace('_',' ')+'; methodology specifies exposure/trip/native basis'
    if name.endswith('_m'): return 'm',name.replace('_',' ')+'; TripInfo or sampled integral as specified in methodology'
    if name.endswith('_count') or name.endswith('_rows') or name.endswith('_trips'): return 'count',name.replace('_',' ')
    return 'native/category/count as named',name.replace('_',' ')+'; native fields follow SUMO XML semantics, aggregate fields follow methodology'
